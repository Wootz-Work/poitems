ok('itemNumber = visual', st.childParts.payload[0].itemNumber===11);
_rowMap=null;
T.head('divergedLockedRows');
spreadsheetData=[mkRow('Child Part','2','D-1')];
st=buildSubmitState(); st.childParts.sent=st.childParts.payload; st.childParts.payload=[];
st.childParts.status='done'; _submitState=st;
ok('clean = no divergence', divergedLockedRows().length===0);
spreadsheetData[0].Quantity.text='99';
ok('detects edited qty', divergedLockedRows().length===1);
spreadsheetData[0].Quantity.text='2'; spreadsheetData[0].Material.text='X';
ok('detects edited material', divergedLockedRows().length===1);
_submitState.childParts.sent=[];
ok('ignores stages with nothing sent', divergedLockedRows().length===0);
T.done();
